// Bundle only local, allowlisted references; the compiler never resolves HTTP or filesystem input.
function bundled(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(bundled);
  if (value && typeof value === "object")
    return Object.fromEntries(
      Object.entries(value).map(([k, v]) => {
        if (k === "$ref") {
          const name = Object.keys(refs).find((name) => refs[name] === v);
          assert.ok(name, `Nonlocal/unresolved reference ${v}`);
          return [k, `#/definitions/${name}`];
        }
        return [k, bundled(v)];
      }),
    );
  return value;
}
