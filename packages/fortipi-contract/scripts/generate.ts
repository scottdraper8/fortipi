function schemaClosure(roots: string[]): string[] {
  const found = new Set<string>();
  function walk(value: unknown): void {
    if (Array.isArray(value)) {
      value.forEach(walk);
      return;
    }
    if (value && typeof value === "object")
      for (const [key, v] of Object.entries(value)) {
        if (key === "$ref") {
          const file = files.find((f) => (v as string).startsWith(`${schemas[f]?.$id}#`));
          assert.ok(file);
          visit(file);
        } else walk(v);
      }
  }
  function visit(file: string): void {
    if (found.has(file)) return;
    found.add(file);
    walk(schemas[file]);
  }
  roots.forEach(visit);
  return [...found].sort();
}
